    private const val PAGE_WIDTH = 595 // Standard A4 points
    private const val PAGE_HEIGHT = 842

    private fun drawBrandHeader(
        context: Context,
        canvas: Canvas,
        paint: Paint,
        businessProfile: BusinessProfile?,
        documentTitle: String,
        documentNumber: String,
        dateFormatted: String
    ) {
        // Deep Navy Header Banner
        paint.color = Color.parseColor("#263849")
        canvas.drawRect(0f, 0f, PAGE_WIDTH.toFloat(), 105f, paint)

        // Accent Stripes: Royal Purple & Secondary Teal
        paint.color = Color.parseColor("#792B87")
        canvas.drawRect(0f, 105f, PAGE_WIDTH.toFloat() * 0.5f, 110f, paint)
        paint.color = Color.parseColor("#299DB2")
        canvas.drawRect(PAGE_WIDTH.toFloat() * 0.5f, 105f, PAGE_WIDTH.toFloat(), 110f, paint)

        // Official White Logo if present
        try {
            val logoBitmap = BitmapFactory.decodeResource(context.resources, R.drawable.logo_compact_white)
            if (logoBitmap != null) {
                val logoH = 28f
                val logoW = logoH * (logoBitmap.width.toFloat() / logoBitmap.height.toFloat())
                val logoDest = RectF(36f, 16f, 36f + logoW, 16f + logoH)
                canvas.drawBitmap(logoBitmap, null, logoDest, paint)
            }
        } catch (_: Exception) {}

        // Company Information
        paint.color = Color.WHITE
        paint.textSize = 13f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        val companyName = businessProfile?.companyName ?: "ADVANCE IMPORT & EXPORT ERP"
        canvas.drawText(companyName, 36f, 64f, paint)

        paint.textSize = 8.5f
        paint.typeface = Typeface.DEFAULT
        paint.color = Color.parseColor("#E2E8F0")
        val address = businessProfile?.address ?: "Motijheel C/A, Dhaka-1000, Bangladesh"
        val contact = "Phone: ${businessProfile?.phone ?: "+880 1711-000000"}  |  Tax/BIN: ${businessProfile?.taxNumber ?: "BIN-99281726-01"}"
        canvas.drawText("$address  |  $contact", 36f, 80f, paint)

        // Document Title & Number Badge on right
        paint.color = Color.WHITE
        paint.textSize = 14f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        val titleWidth = paint.measureText(documentTitle)
        canvas.drawText(documentTitle, PAGE_WIDTH - 36f - titleWidth, 46f, paint)

        paint.textSize = 9.5f
        paint.typeface = Typeface.DEFAULT
        paint.color = Color.parseColor("#E2E8F0")
        val numWidth = paint.measureText(documentNumber)
        canvas.drawText(documentNumber, PAGE_WIDTH - 36f - numWidth, 66f, paint)

        val dateWidth = paint.measureText("Date: $dateFormatted")
        canvas.drawText("Date: $dateFormatted", PAGE_WIDTH - 36f - dateWidth, 82f, paint)
    }

    private fun drawFooter(canvas: Canvas, paint: Paint, pageNumber: Int, totalPages: Int) {
        paint.color = Color.parseColor("#CBD5E1")
        canvas.drawLine(36f, PAGE_HEIGHT - 40f, PAGE_WIDTH - 36f, PAGE_HEIGHT - 40f, paint)

        paint.color = Color.parseColor("#64748B")
        paint.textSize = 8f
        paint.typeface = Typeface.DEFAULT
        canvas.drawText("Generated by ADVANCE ERP • ISO 9001 / GAAP Compliant Inventory Engine", 36f, PAGE_HEIGHT - 26f, paint)

        val pageStr = "Page $pageNumber of $totalPages"
        val pw = paint.measureText(pageStr)
        canvas.drawText(pageStr, PAGE_WIDTH - 36f - pw, PAGE_HEIGHT - 26f, paint)
    }

    fun generateValuationPdf(
        context: Context,
        profile: BusinessProfile?,
        breakdown: InventoryValuationBreakdown,
        language: AppLanguage,
        currency: CurrencyCode
    ): File {
        val document = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, 1).create()
        val page = document.startPage(pageInfo)
        val canvas = page.canvas
        val paint = Paint(Paint.ANTI_ALIAS_FLAG)

        val dateFormat = SimpleDateFormat("dd MMM yyyy, HH:mm", Locale.US)
        val dateFormatted = dateFormat.format(Date())

        val title = if (language == AppLanguage.BANGLA) "মজুদ মূল্যায়ন প্রতিবেদন" else "INVENTORY VALUATION REPORT"
        val docNum = "VAL-${System.currentTimeMillis() % 1000000}"

        drawBrandHeader(context, canvas, paint, profile, title, docNum, dateFormatted)

        var y = 135f

        // Summary Metric Cards
        paint.color = Color.parseColor("#F8FAFC")
        val summaryRect = RectF(36f, y, PAGE_WIDTH - 36f, y + 80f)
        canvas.drawRoundRect(summaryRect, 10f, 10f, paint)
        paint.style = Paint.Style.STROKE
        paint.color = Color.parseColor("#E2E8F0")
        canvas.drawRoundRect(summaryRect, 10f, 10f, paint)
        paint.style = Paint.Style.FILL

        // Sellable Inventory
        paint.textSize = 9f
        paint.color = Color.parseColor("#64748B")
        canvas.drawText(if (language == AppLanguage.BANGLA) "বিক্রয়যোগ্য মজুদ" else "Sellable Stock", 50f, y + 25f, paint)
        paint.textSize = 13f
        paint.color = Color.parseColor("#0F172A")
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("${breakdown.sellableQuantity} units", 50f, y + 45f, paint)
        paint.textSize = 10f
        paint.color = Color.parseColor("#299DB2")
        canvas.drawText(Formatters.formatCurrency(breakdown.sellableValuationMinor, currency, language), 50f, y + 65f, paint)

        // Damaged Stock
        paint.typeface = Typeface.DEFAULT
        paint.textSize = 9f
        paint.color = Color.parseColor("#64748B")
        canvas.drawText(if (language == AppLanguage.BANGLA) "নষ্ট ও অবলোপন" else "Damaged / Write-Off", 220f, y + 25f, paint)
        paint.textSize = 13f
        paint.color = Color.parseColor("#DC2626")
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("${breakdown.damagedQuantity} units", 220f, y + 45f, paint)
        paint.textSize = 10f
        paint.color = Color.parseColor("#DC2626")
        canvas.drawText(Formatters.formatCurrency(breakdown.damagedValuationMinor, currency, language), 220f, y + 65f, paint)

        // Total Valuation
        paint.typeface = Typeface.DEFAULT
        paint.textSize = 9f
        paint.color = Color.parseColor("#64748B")
        canvas.drawText(if (language == AppLanguage.BANGLA) "মোট মজুদ মূল্যায়ন (FIFO)" else "Total Valuation (FIFO)", 380f, y + 25f, paint)
        paint.textSize = 13f
        paint.color = Color.parseColor("#792B87")
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("${breakdown.sellableQuantity + breakdown.inTransitQuantity} units", 380f, y + 45f, paint)
        paint.textSize = 11f
        canvas.drawText(Formatters.formatCurrency(breakdown.totalValuationMinor, currency, language), 380f, y + 65f, paint)

        y += 105f

        // Warehouse Breakdown Table Header
        paint.textSize = 11f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.color = Color.parseColor("#0F172A")
        canvas.drawText(if (language == AppLanguage.BANGLA) "ওয়্যারহাউস-ভিত্তিক বিবরণ" else "Warehouse Valuation Breakdown", 36f, y, paint)

        y += 14f
        paint.color = Color.parseColor("#263849")
        canvas.drawRect(36f, y, PAGE_WIDTH - 36f, y + 24f, paint)

        paint.color = Color.WHITE
        paint.textSize = 9f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("Warehouse", 46f, y + 16f, paint)
        canvas.drawText("Physical Qty", 220f, y + 16f, paint)
        canvas.drawText("Sellable Qty", 310f, y + 16f, paint)
        canvas.drawText("Damaged Qty", 400f, y + 16f, paint)
        val valColTitle = "Valuation"
        canvas.drawText(valColTitle, PAGE_WIDTH - 46f - paint.measureText(valColTitle), y + 16f, paint)

        y += 24f

        paint.typeface = Typeface.DEFAULT
        paint.textSize = 8.5f

        breakdown.warehouseBreakdown.forEachIndexed { index, wh ->
            paint.color = if (index % 2 == 0) Color.WHITE else Color.parseColor("#F8FAFC")
            canvas.drawRect(36f, y, PAGE_WIDTH - 36f, y + 22f, paint)

            paint.color = Color.parseColor("#0F172A")
            canvas.drawText(wh.warehouseName, 46f, y + 15f, paint)
            canvas.drawText("${wh.physicalQuantity}", 220f, y + 15f, paint)
            canvas.drawText("${wh.sellableQuantity}", 310f, y + 15f, paint)
            canvas.drawText("${wh.damagedQuantity}", 400f, y + 15f, paint)

            val valStr = Formatters.formatCurrency(wh.valuationMinor, currency, language)
            canvas.drawText(valStr, PAGE_WIDTH - 46f - paint.measureText(valStr), y + 15f, paint)

            paint.color = Color.parseColor("#E2E8F0")
            canvas.drawLine(36f, y + 22f, PAGE_WIDTH - 36f, y + 22f, paint)
            y += 22f
        }

        drawFooter(canvas, paint, 1, 1)
        document.finishPage(page)

        val file = File(context.cacheDir, "Inventory_Valuation_${System.currentTimeMillis()}.pdf")
        FileOutputStream(file).use { out -> document.writeTo(out) }
        document.close()
        return file
    }

    fun generateMovementLedgerPdf(
        context: Context,
        profile: BusinessProfile?,
        movements: List<StockMovementWithDetails>,
        language: AppLanguage,
        currency: CurrencyCode
    ): File {
        val document = PdfDocument()
        val itemsPerPage = 22
        val totalPages = (movements.size + itemsPerPage - 1) / itemsPerPage.coerceAtLeast(1)

        val dateFormat = SimpleDateFormat("dd/MM/yyyy HH:mm", Locale.US)
        val dateFormatted = dateFormat.format(Date())

        val title = if (language == AppLanguage.BANGLA) "স্টক মুভমেন্ট অডিট লেজার" else "STOCK MOVEMENT AUDIT TRAIL"
        val docNum = "MOV-LEDGER-${System.currentTimeMillis() % 1000000}"

        for (pageIdx in 0 until totalPages.coerceAtLeast(1)) {
            val pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, pageIdx + 1).create()
            val page = document.startPage(pageInfo)
            val canvas = page.canvas
            val paint = Paint(Paint.ANTI_ALIAS_FLAG)

            drawBrandHeader(context, canvas, paint, profile, title, docNum, dateFormatted)

            var y = 130f

            // Table Header
            paint.color = Color.parseColor("#263849")
            canvas.drawRect(36f, y, PAGE_WIDTH - 36f, y + 22f, paint)

            paint.color = Color.WHITE
            paint.textSize = 8.5f
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)

            canvas.drawText("Date & Movement #", 42f, y + 15f, paint)
            canvas.drawText("Product & SKU", 170f, y + 15f, paint)
            canvas.drawText("Type", 320f, y + 15f, paint)
            canvas.drawText("Qty", 390f, y + 15f, paint)
            canvas.drawText("Run Bal", 440f, y + 15f, paint)
            val costHeader = "Cost Impact"
            canvas.drawText(costHeader, PAGE_WIDTH - 42f - paint.measureText(costHeader), y + 15f, paint)

            y += 22f

            val startIndex = pageIdx * itemsPerPage
            val endIndex = minOf(startIndex + itemsPerPage, movements.size)

            paint.typeface = Typeface.DEFAULT
            paint.textSize = 8f

            for (i in startIndex until endIndex) {
                val mov = movements[i]
                val isEven = (i - startIndex) % 2 == 0
                paint.color = if (isEven) Color.WHITE else Color.parseColor("#F8FAFC")
                canvas.drawRect(36f, y, PAGE_WIDTH - 36f, y + 24f, paint)

                paint.color = Color.parseColor("#0F172A")
                val movDate = SimpleDateFormat("dd/MM/yy", Locale.US).format(Date(mov.createdAt))
                canvas.drawText("$movDate  ${mov.movementNumber.take(14)}", 42f, y + 11f, paint)
                paint.color = Color.parseColor("#64748B")
                paint.textSize = 7f
                canvas.drawText(mov.warehouseName, 42f, y + 20f, paint)

                paint.textSize = 8f
                paint.color = Color.parseColor("#0F172A")
                canvas.drawText(mov.productNameEn.take(24), 170f, y + 11f, paint)
                paint.color = Color.parseColor("#64748B")
                paint.textSize = 7f
                canvas.drawText("SKU: ${mov.baseSku}", 170f, y + 20f, paint)

                paint.textSize = 7.5f
                paint.color = Color.parseColor("#475569")
                canvas.drawText(mov.movementType.replace("_", " "), 320f, y + 15f, paint)

                val isInc = mov.movementType.contains("RECEIPT") || mov.movementType.contains("IN") || mov.movementType.contains("RETURN")
                paint.textSize = 8.5f
                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                paint.color = if (isInc) Color.parseColor("#16A34A") else Color.parseColor("#DC2626")
                val qtyStr = (if (isInc) "+" else "-") + "${mov.quantity}"
                canvas.drawText(qtyStr, 390f, y + 15f, paint)

                paint.typeface = Typeface.DEFAULT
                paint.color = Color.parseColor("#0F172A")
                canvas.drawText("${mov.balanceAfterMovement}", 440f, y + 15f, paint)

                val costStr = Formatters.formatCurrency(mov.totalCostImpactMinor, currency, language)
                canvas.drawText(costStr, PAGE_WIDTH - 42f - paint.measureText(costStr), y + 15f, paint)

                paint.color = Color.parseColor("#E2E8F0")
                canvas.drawLine(36f, y + 24f, PAGE_WIDTH - 36f, y + 24f, paint)
                y += 24f
            }

            drawFooter(canvas, paint, pageIdx + 1, totalPages.coerceAtLeast(1))
            document.finishPage(page)
        }

        val file = File(context.cacheDir, "Movement_Ledger_${System.currentTimeMillis()}.pdf")
        FileOutputStream(file).use { out -> document.writeTo(out) }
        document.close()
        return file
    }

    fun generateReconciliationPdf(
        context: Context,
        profile: BusinessProfile?,
        reconciliation: InventoryReconciliation,
        items: List<InventoryReconciliationItemWithDetails>,
        language: AppLanguage,
        currency: CurrencyCode
    ): File {
        val document = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, 1).create()
        val page = document.startPage(pageInfo)
        val canvas = page.canvas
        val paint = Paint(Paint.ANTI_ALIAS_FLAG)

        val dateFormat = SimpleDateFormat("dd MMM yyyy, HH:mm", Locale.US)
        val dateFormatted = dateFormat.format(Date(reconciliation.createdAt))

        val title = if (language == AppLanguage.BANGLA) "মজুদ পুনর্মিলন নিরীক্ষা প্রতিবেদন" else "INVENTORY RECONCILIATION AUDIT"

        drawBrandHeader(context, canvas, paint, profile, title, reconciliation.reconciliationNumber, dateFormatted)

        var y = 135f

        // Status Banner
        val isMatched = reconciliation.status == "MATCHED"
        paint.color = if (isMatched) Color.parseColor("#ECFDF5") else Color.parseColor("#FEF2F2")
        val statusRect = RectF(36f, y, PAGE_WIDTH - 36f, y + 36f)
        canvas.drawRoundRect(statusRect, 8f, 8f, paint)
        paint.style = Paint.Style.STROKE
        paint.color = if (isMatched) Color.parseColor("#10B981") else Color.parseColor("#EF4444")
        canvas.drawRoundRect(statusRect, 8f, 8f, paint)
        paint.style = Paint.Style.FILL

        paint.textSize = 11f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.color = if (isMatched) Color.parseColor("#065F46") else Color.parseColor("#991B1B")
        val statusText = if (isMatched) "AUDIT STATUS: FULLY RECONCILED (NO DISCREPANCIES)" else "AUDIT STATUS: DISCREPANCIES DETECTED IN INVENTORY BALANCES"
        canvas.drawText(statusText, 48f, y + 23f, paint)

        y += 50f

        // 5-Way Balance Summary Cards
        paint.color = Color.parseColor("#F8FAFC")
        val boxRect = RectF(36f, y, PAGE_WIDTH - 36f, y + 90f)
        canvas.drawRoundRect(boxRect, 10f, 10f, paint)
        paint.style = Paint.Style.STROKE
        paint.color = Color.parseColor("#E2E8F0")
        canvas.drawRoundRect(boxRect, 10f, 10f, paint)
        paint.style = Paint.Style.FILL

        // 1. Stock Balances
        paint.textSize = 8.5f
        paint.typeface = Typeface.DEFAULT
        paint.color = Color.parseColor("#64748B")
        canvas.drawText("1. Stock Balances", 48f, y + 25f, paint)
        paint.textSize = 12f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.color = Color.parseColor("#0F172A")
        canvas.drawText("${reconciliation.totalStockBalanceQty} units", 48f, y + 45f, paint)

        // 2. Movement Net
        paint.textSize = 8.5f
        paint.typeface = Typeface.DEFAULT
        paint.color = Color.parseColor("#64748B")
        canvas.drawText("2. Net Movements", 150f, y + 25f, paint)
        paint.textSize = 12f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.color = Color.parseColor("#0F172A")
        canvas.drawText("${reconciliation.totalMovementQty} units", 150f, y + 45f, paint)

        // 3. FIFO Layers Qty
        paint.textSize = 8.5f
        paint.typeface = Typeface.DEFAULT
        paint.color = Color.parseColor("#64748B")
        canvas.drawText("3. FIFO Active Qty", 260f, y + 25f, paint)
        paint.textSize = 12f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.color = Color.parseColor("#0F172A")
        canvas.drawText("${reconciliation.totalFifoRemainingQty} units", 260f, y + 45f, paint)

        // 4. FIFO Valuation
        paint.textSize = 8.5f
        paint.typeface = Typeface.DEFAULT
        paint.color = Color.parseColor("#64748B")
        canvas.drawText("4. FIFO Valuation", 370f, y + 25f, paint)
        paint.textSize = 11f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.color = Color.parseColor("#792B87")
        canvas.drawText(Formatters.formatCurrency(reconciliation.totalFifoValuationMinor, currency, language), 370f, y + 45f, paint)

        // 5. Account 1210 GL
        paint.textSize = 8.5f
        paint.typeface = Typeface.DEFAULT
        paint.color = Color.parseColor("#64748B")
        canvas.drawText("5. Acc 1210 (GL)", 470f, y + 25f, paint)
        paint.textSize = 11f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.color = Color.parseColor("#299DB2")
        canvas.drawText(Formatters.formatCurrency(reconciliation.account1210BalanceMinor, currency, language), 470f, y + 45f, paint)

        // Discrepancy Footnote
        paint.textSize = 9f
        paint.color = if (isMatched) Color.parseColor("#16A34A") else Color.parseColor("#DC2626")
        canvas.drawText(
            "Quantity Variance: ${reconciliation.quantityDiscrepancy} units  |  Valuation Variance: ${Formatters.formatCurrency(reconciliation.valuationDiscrepancyMinor, currency, language)}",
            48f,
            y + 75f,
            paint
        )

        y += 110f

        // Product Line Item Discrepancies Table
        paint.textSize = 11f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.color = Color.parseColor("#0F172A")
        canvas.drawText("Reconciliation Items & Audit Status (${items.size})", 36f, y, paint)

        y += 14f
        paint.color = Color.parseColor("#263849")
        canvas.drawRect(36f, y, PAGE_WIDTH - 36f, y + 22f, paint)

        paint.color = Color.WHITE
        paint.textSize = 8.5f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("Product", 46f, y + 15f, paint)
        canvas.drawText("Warehouse", 190f, y + 15f, paint)
        canvas.drawText("Stock Bal", 280f, y + 15f, paint)
        canvas.drawText("Move Net", 340f, y + 15f, paint)
        canvas.drawText("FIFO Qty", 400f, y + 15f, paint)
        canvas.drawText("Audit Flag", PAGE_WIDTH - 46f - paint.measureText("Audit Flag"), y + 15f, paint)

        y += 22f
        paint.typeface = Typeface.DEFAULT
        paint.textSize = 8f

        val displayItems = items.take(18)
        displayItems.forEachIndexed { idx, itm ->
            paint.color = if (idx % 2 == 0) Color.WHITE else Color.parseColor("#F8FAFC")
            canvas.drawRect(36f, y, PAGE_WIDTH - 36f, y + 20f, paint)

            paint.color = Color.parseColor("#0F172A")
            canvas.drawText(itm.productNameEn.take(22), 46f, y + 14f, paint)
            canvas.drawText(itm.warehouseName.take(16), 190f, y + 14f, paint)
            canvas.drawText("${itm.stockBalanceQty}", 280f, y + 14f, paint)
            canvas.drawText("${itm.movementNetQty}", 340f, y + 14f, paint)
            canvas.drawText("${itm.fifoRemainingQty}", 400f, y + 14f, paint)

            val flagText = if (itm.qtyMismatch) "MISMATCH" else "OK"
            paint.color = if (itm.qtyMismatch) Color.parseColor("#DC2626") else Color.parseColor("#16A34A")
            canvas.drawText(flagText, PAGE_WIDTH - 46f - paint.measureText(flagText), y + 14f, paint)

            paint.color = Color.parseColor("#E2E8F0")
            canvas.drawLine(36f, y + 20f, PAGE_WIDTH - 36f, y + 20f, paint)
            y += 20f
        }

        drawFooter(canvas, paint, 1, 1)
        document.finishPage(page)

        val file = File(context.cacheDir, "Reconciliation_${reconciliation.reconciliationNumber}.pdf")
        FileOutputStream(file).use { out -> document.writeTo(out) }
        document.close()
        return file
    }

    fun sharePdf(context: Context, file: File, title: String) {
        val uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            file
        )
        val shareIntent = Intent(Intent.ACTION_SEND).apply {
            type = "application/pdf"
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, title)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(Intent.createChooser(shareIntent, title).apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        })
    }
